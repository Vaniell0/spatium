const Element& element(int Z) {
    if (Z < 1 || Z > ELEMENT_COUNT)
        throw std::out_of_range("Element Z=" + std::to_string(Z) + " not in database");
    return elements_table[Z - 1];
}

const Element& element(std::string_view symbol) {
    for (int i = 0; i < ELEMENT_COUNT; ++i)
        if (elements_table[i].symbol == symbol)
            return elements_table[i];
    throw std::out_of_range("Element '" + std::string(symbol) + "' not found");
}

