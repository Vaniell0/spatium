// Can a field be identified without naming it? Measured, not assumed.
//
// This file answers a design question rather than a performance one, and
// it lives next to bench_trace.cpp rather than inside it for exactly
// that reason: the two ask different things and should not die together
// in a refactor of one.
//
// The question. A structural field representation wants to say "these
// two fields are the same function" so it can share a cache entry, share
// a lowered kernel, and hoist a parameter table out of N copies. The
// obvious discriminator is the address of the erased callable, and that
// is wrong: examples/donut_demo.cpp builds 19 800 dust motions from one
// lambda written once inside a loop, and they live at 19 800 different
// addresses. By address they are 19 800 different functions; by any
// honest reading they are one function with 19 800 parameter sets, and a
// design that cannot tell the difference buys nothing on the only scene
// we actually have.
//
// The measurement, run against the real demo on a scratch branch before
// any of this was designed:
//
//     39 611 field instances installed on nodes, 6 distinct closure types
//        19 800 instances  capturing   (dust motion)
//        19 800 instances  capturing   (dust color)
//             8 instances  stateless   (grow_scale, shared by dough/icing/sprinkles)
//             1 instance   stateless   (cube motion)
//             1 instance   capturing   (dough bump thickness)
//             1 instance   capturing   (icing thickness)
//
// 6 602 field instances per distinct function. So the opportunity is
// real, and typeid of the closure type is what sees it: identical for
// every instance of one lambda, different for genuinely different ones,
// independent of where the object sits, and -- the part that matters --
// generated by the compiler, so it costs the user nothing and opens no
// door to registering, versioning or standardising function *names*.
//
// What this file guards is the language-level invariant that result
// rests on, because the design is about to depend on it:
//
//   1. A lambda written once inside a loop is ONE type, however many
//      instances the loop constructs.
//   2. Two separately written lambdas are different types even when
//      their bodies are identical.
//   3. A capturing closure is distinguishable from a stateless one
//      without asking the user, via std::is_empty_v.
//
// (3) is not a detail. Identity by type alone is sound only for a
// stateless closure, where every instance really is interchangeable. For
// a capturing one the state that makes instances differ is hidden inside
// the object, so deduplicating on type would silently fuse 19 800
// particles into one trajectory -- a correct answer under the assumption
// that the capture is empty and a wrong one otherwise, which is the same
// shape as a NaN walking through a filter phrased to skip rather than to
// keep. Hence the rule the design takes: deduplication is promised for
// stateless leaves, and for parameterised leaves on (type, params); a
// capturing leaf with no parameters is opaque and is never deduplicated.
//
// It runs in the default pass, at one iteration. Google Benchmark has no
// register-but-skip, and the cheap alternatives -- a separate target, a
// filter someone has to remember -- would make this a check that only
// runs when asked, which is how "separately, later" becomes "never". It
// costs microseconds and reports a property rather than a timing, so the
// honest tradeoff is to let it run:
//     ./spatium_bench --benchmark_filter=FieldIdentity   # just this one

#include <benchmark/benchmark.h>
#include <spatium/algebra/vector.hpp>
#include <cstddef>
#include <set>
#include <type_traits>
#include <typeindex>
#include <typeinfo>
#include <vector>

using namespace spatium;

namespace {

using V3 = Vec<double, 3>;

struct FieldIdentity {
    std::type_index type;
    bool stateless;
};

template<class F>
FieldIdentity identify(const F&) {
    return {std::type_index(typeid(F)), std::is_empty_v<F>};
}

// The demo's dominant shape: one lambda, written once, constructed once
// per particle with different captured values each time.
std::vector<FieldIdentity> per_instance_captures(std::size_t n) {
    std::vector<FieldIdentity> out;
    out.reserve(n);
    for (std::size_t i = 0; i < n; ++i) {
        V3 burst{static_cast<double>(i), 0.0, 0.0};
        double seed = static_cast<double>(i) * 0.5;
        auto motion = [burst, seed](const V3& p, double t) {
            return V3{p + burst * (t * seed)};
        };
        out.push_back(identify(motion));
    }
    return out;
}

} // namespace

static void BM_FieldIdentity(benchmark::State& state) {
    constexpr std::size_t particles = 19800;

    auto captured = per_instance_captures(particles);
    std::set<std::type_index> distinct;
    for (const auto& f : captured) distinct.insert(f.type);

    // (1) One lambda in a loop is one type, not one per instance. This
    //     is the whole basis for a parameter table replacing N closures.
    if (distinct.size() != 1)
        state.SkipWithError("a lambda written once in a loop produced more than one type");
    // ... and it is correctly reported as carrying hidden state, so
    //     identity by type alone must not be enough to fuse them.
    for (const auto& f : captured)
        if (f.stateless) { state.SkipWithError("a capturing closure reported as stateless"); break; }

    // (2) Identical bodies, written twice, are two types. A false
    //     positive here would fuse fields that only look alike.
    auto a = [](const V3& p, double t) { return V3{p * t}; };
    auto b = [](const V3& p, double t) { return V3{p * t}; };
    if (identify(a).type == identify(b).type)
        state.SkipWithError("two separately written lambdas collapsed to one type");

    // (3) A stateless closure is recognisable as such without being
    //     told, which is what makes deduplicating it sound.
    if (!identify(a).stateless)
        state.SkipWithError("a capture-less lambda not reported as stateless");

    for (auto _ : state) {
        benchmark::DoNotOptimize(distinct.size());
        state.PauseTiming();
        state.SetLabel(std::to_string(captured.size()) + " instances, " +
                       std::to_string(distinct.size()) + " distinct type" +
                       (distinct.size() == 1 ? "" : "s"));
        state.ResumeTiming();
    }
}
BENCHMARK(BM_FieldIdentity)->Iterations(1);
